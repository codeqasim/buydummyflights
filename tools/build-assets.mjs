// BUILD STEP RUN BY wrangler (build.command), SO LOCAL AND WORKERS BUILDS GET THE SAME OUTPUT: i18n INDEX, TAILWIND CSS, SELF-HOSTED VENDOR JS + FONT, CONTENT HASHES.
import { execFileSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const p = (...a) => join(root, ...a)
const run = (bin, args) => execFileSync(p('node_modules/.bin', bin), args, { cwd: root, stdio: 'inherit' })

execFileSync(process.execPath, [p('tools/i18n.mjs')], { cwd: root, stdio: 'inherit' })

mkdirSync(p('public/assets/css'), { recursive: true })
run('tailwindcss', ['-i', 'styles/input.css', '-o', 'public/assets/css/app.css', '--minify'])

// VENDOR: ALPINE IS SELF-HOSTED SO THE CSP NEEDS NO THIRD-PARTY ORIGIN. THE CSP BUILD AVOIDS new Function().
mkdirSync(p('public/assets/js/vendor'), { recursive: true })
copyFileSync(p('node_modules/@alpinejs/csp/dist/cdn.min.js'), p('public/assets/js/vendor/alpine.js'))
copyFileSync(p('node_modules/@alpinejs/intersect/dist/cdn.min.js'), p('public/assets/js/vendor/alpine-intersect.js'))
mkdirSync(p('public/assets/fonts'), { recursive: true })
copyFileSync(p('node_modules/@fontsource-variable/plus-jakarta-sans/files/plus-jakarta-sans-latin-wght-normal.woff2'), p('public/assets/fonts/plus-jakarta-sans-latin-wght-normal.woff2'))

// HASHES: ?v=<8 hex> LETS public/_headers CACHE ASSETS FOR A YEAR AND STILL SHIP FIXES.
const files = ['/assets/css/app.css', '/assets/js/theme.js', '/assets/js/app.js', '/assets/js/vendor/alpine.js', '/assets/js/vendor/alpine-intersect.js']
const map = Object.fromEntries(files.map((f) => [f, createHash('sha256').update(readFileSync(p('public', f))).digest('hex').slice(0, 8)]))
const out = `// GENERATED by tools/build-assets.mjs: CONTENT HASHES FOR ?v= CACHE BUSTING. NEVER EDIT BY HAND.\nexport const assetVersion: Record<string, string> = ${JSON.stringify(map, null, 2)}\n`
// WRITE ONLY ON CHANGE: wrangler dev WATCHES app/, AND AN UNCONDITIONAL WRITE WOULD RESTART IT IN A LOOP.
let prev = ''
try { prev = readFileSync(p('app/data/assets.ts'), 'utf8') } catch {}
if (prev !== out) writeFileSync(p('app/data/assets.ts'), out)
console.log('assets: built', Object.keys(map).length, 'hashed files')
