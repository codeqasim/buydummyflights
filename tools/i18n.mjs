// GENERATES app/i18n/messages/index.ts AND CHECKS EVERY LANGUAGE FILE AGAINST ENGLISH. `--check` EXITS 1 ON ANY GAP.
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs'
import { join } from 'node:path'

const root = new URL('../app/i18n/messages/', import.meta.url).pathname
const check = process.argv.includes('--check')
const nss = readdirSync(root, { withFileTypes: true }).filter((d) => d.isDirectory()).map((d) => d.name).sort()
const langs = ['en']

const flat = (o, p = '') =>
  Object.entries(o).flatMap(([k, v]) =>
    v && typeof v === 'object' && !Array.isArray(v) ? flat(v, `${p}${k}.`) : [`${p}${k}`],
  )

let gaps = 0
for (const ns of nss) {
  const base = flat(JSON.parse(readFileSync(join(root, ns, 'en.json'), 'utf8')))
  for (const l of langs) {
    const f = join(root, ns, `${l}.json`)
    if (!existsSync(f)) { console.error(`missing ${ns}/${l}.json`); gaps++; continue }
    const keys = new Set(flat(JSON.parse(readFileSync(f, 'utf8'))))
    for (const k of base) if (!keys.has(k)) { console.error(`gap: ${l}/${ns}: ${k}`); gaps++ }
  }
}

const ident = (s) => s.replace(/[^a-zA-Z0-9]/g, '_')
let out = '// GENERATED by tools/i18n.mjs (npm run i18n). NEVER EDIT BY HAND.\n'
for (const ns of nss) for (const l of langs) out += `import ${ident(ns)}_${l} from './${ns}/${l}.json'\n`
out += '\nexport const messages: Record<string, Record<string, unknown>> = {\n'
for (const ns of nss) out += `  ${JSON.stringify(ns)}: { ${langs.map((l) => `${l}: ${ident(ns)}_${l}`).join(', ')} },\n`
out += '}\n'
writeFileSync(join(root, 'index.ts'), out)
console.log(`i18n: ${nss.length} namespaces, ${gaps} gaps`)
if (check && gaps) process.exit(1)
